async def seed():
    criadas = 0
    existentes = 0
    async with async_session() as db:
        for dados in EMPRESAS:
            email = dados["email"]
            existe = (await db.execute(select(User).where(User.email == email))).scalar_one_or_none()
            if existe:
                existentes += 1
                print(f"[skip] {email} já existe")
                continue
            user = User(
                nome=dados["nome"],
                email=email,
                telefone=dados["telefone"],
                password_hash=hash_password(PASSWORD),
                tipo_conta="empresa",
                localizacao=dados["localizacao"],
                latitude=dados["latitude"],
                longitude=dados["longitude"],
                nif=dados["nif"],
                area_atuacao=dados["area_atuacao"],
                nome_comercial=dados["nome_comercial"],
                tipo_entidade=dados["tipo_entidade"],
                descricao=dados["descricao"],
                especialidades=dados["especialidades"],
                anos_experiencia=dados["anos_experiencia"],
                provincia=dados["provincia"],
                municipio=dados["municipio"],
                bairro=dados["bairro"],
                endereco=dados["endereco"],
                ponto_referencia=dados["ponto_referencia"],
                categorias_servico=dados["categorias_servico"],
                areas_atendidas=dados["areas_atendidas"],
                atende_estabelecimento=dados["atende_estabelecimento"],
                atende_domicilio=dados["atende_domicilio"],
                atendimento_24h=dados["atendimento_24h"],
                raio_atuacao=dados["raio_atuacao"],
                website=dados.get("website"),
                telefone_whatsapp=dados["telefone_whatsapp"],
                status_atendimento=dados["status_atendimento"],
                status_verificacao=dados["status_verificacao"],
                verificado=dados["verificado"],
                representante_nome=dados["representante_nome"],
                representante_cargo=dados["representante_cargo"],
                representante_telefone=dados["representante_telefone"],
            )
            db.add(user)
            criadas += 1
            print(f"[ok] {email} criada")
        await db.commit()
    print(f"\nCriadas: {criadas} | Já existentes: {existentes}")


if __name__ == "__main__":
    asyncio.run(seed())